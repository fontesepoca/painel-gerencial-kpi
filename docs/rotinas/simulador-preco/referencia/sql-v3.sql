--
-- Em relação à v2 (sql-v2.sql, guardada ao lado, NÃO por cima):
--   - B.CLASSEVENDA passa a sair como CLASSE_GIRO_EST (classe de giro de estoque);
--   - coluna nova B.CLASSE AS CLASSE_COMISSAO (P.CLASSE, classe de comissão);
--   - o SELECT de fora com CCLASSTRIB e CST da PCTRIBUTACAO (LEFT JOIN TR2), o mesmo que foi
--     encaminhado ao gestor em 25/11/2026.
-- Nenhuma conta mudou.
--
-- NÃO EDITAR. É a referência contra a qual a API é conferida (sp5, com a adaptação A9 para o
-- SELECT de fora).
